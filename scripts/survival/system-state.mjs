/**
 * scripts/survival/system-state.mjs
 *
 * Generates .data/SYSTEM-STATE.md — single source of truth for what is
 * actually running, wired, alive vs orphan. Pure read, no mutation.
 *
 * Contents:
 *   - All long-running processes + uptime
 *   - cortex-alive heartbeat snapshot
 *   - survival_loop status (armed, contract, strategies)
 *   - Opportunity pipeline state
 *   - Outbound approval queue
 *   - Lead database stats
 *   - Wiki brain stats
 *   - Recent bus traffic summary
 *   - Last 24h cost
 */

import { readFileSync, existsSync, readdirSync, writeFileSync, statSync, mkdirSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import Database from "better-sqlite3";
import { execSync } from "node:child_process";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, "../..");
const OUT = resolve(ROOT, ".data/SYSTEM-STATE.md");

function safeRead(p) { try { return readFileSync(p, "utf-8"); } catch { return null; } }
function safeJson(p) { try { return JSON.parse(readFileSync(p, "utf-8")); } catch { return null; } }
function pidAlive(pid) { try { execSync(`ps -p ${pid}`, { stdio: "ignore" }); return true; } catch { return false; } }

const lines = [];
function H(s) { lines.push(`## ${s}\n`); }
function P(s) { lines.push(s); }

P(`# SYSTEM STATE\n`);
P(`generated: ${new Date().toISOString()}\n`);
P(`This file is auto-generated by scripts/survival/system-state.mjs. Do not hand-edit.\n`);

// --- Long-running processes ---
H("Live processes (long-running daemons)");
const pidFiles = [
  ["cortex-alive (36 cortex modules holder)", ".data/cortex-alive.pid"],
  ["cortex-daemon (legacy business loop)", ".data/cortex-daemon.pid"],
  ["pulse-daemon (hourly orchestrator)", ".data/pulse-daemon.pid"],
  ["obsidian-sync (wiki -> obsidian)", ".data/obsidian-sync.pid"],
  ["organism-respond (telegram listener)", ".data/organism-respond.pid"],
  ["sonnet-bots-daemon", ".data/sonnet-bots-daemon.pid"],
];
P("| daemon | pid | alive | pid file |");
P("|---|---|---|---|");
for (const [name, file] of pidFiles) {
  const pid = safeRead(resolve(ROOT, file))?.trim();
  if (!pid) { P(`| ${name} | _missing_ | _no pid file_ | \`${file}\` |`); continue; }
  P(`| ${name} | ${pid} | ${pidAlive(pid) ? "ALIVE" : "DEAD"} | \`${file}\` |`);
}
P("");

// --- cortex-alive heartbeat ---
H("Cortex-alive heartbeat (the unified bus carrier)");
const hb = safeJson(resolve(ROOT, ".data/cortex-alive-heartbeat.json"));
if (hb) {
  P(`- uptime: ${Math.round(hb.uptime_seconds / 60)} min`);
  P(`- modules registered: ${hb.modules_registered}`);
  P(`- boot failures: ${hb.boot_failures}`);
  P(`- bus events lifetime: ${hb.bus_event_count_total}`);
  P(`- top sources: ${Object.entries(hb.top_sources || {}).map(([k, v]) => `${k}(${v})`).join(", ")}`);
  P(`- top types: ${Object.entries(hb.top_types || {}).map(([k, v]) => `${k}(${v})`).join(", ")}`);
} else {
  P(`(no heartbeat file — cortex-alive may not be running)`);
}
P("");

// --- Survival loop status ---
H("Survival_loop status");
const surv = safeJson(resolve(ROOT, ".data/cortex-affect-state.json"));
const armed = existsSync(resolve(ROOT, ".data/survival-armed.flag"));
const contractMd = safeRead(resolve(ROOT, "scripts/survival/contract.md"));
P(`- armed: ${armed}`);
P(`- contract.md exists: ${contractMd ? "yes (" + contractMd.length + " chars)" : "MISSING"}`);
let strategyStats = { active: 0, probation: 0, retired: 0 };
let outcomeRows = 0;
let llmSpend24h = 0;
try {
  const db = new Database(resolve(ROOT, ".data/survival.db"), { readonly: true });
  for (const r of db.prepare(`SELECT status, COUNT(*) AS n FROM policy_strategies GROUP BY status`).all()) {
    strategyStats[r.status] = r.n;
  }
  outcomeRows = db.prepare(`SELECT COUNT(*) AS n FROM llm_call_log`).get()?.n || 0;
  llmSpend24h = db.prepare(`SELECT COALESCE(SUM(cost_usd),0) AS total FROM llm_call_log WHERE ts >= datetime('now','-24 hours')`).get()?.total || 0;
  db.close();
} catch {}
P(`- strategies: ${strategyStats.active} active, ${strategyStats.probation} probation, ${strategyStats.retired} retired`);
P(`- llm_call_log rows total: ${outcomeRows}`);
P(`- llm spend last 24h: $${llmSpend24h.toFixed(4)} (cap $3.65 USD = 5 CAD)`);
P("");

// --- Opportunity pipeline ---
H("Opportunity pipeline");
try {
  const db = new Database(resolve(ROOT, ".data/survival.db"), { readonly: true });
  const opps = db.prepare(`SELECT state, COUNT(*) AS n FROM opportunities GROUP BY state`).all();
  if (opps.length === 0) P(`(no opportunities yet)`);
  else for (const o of opps) P(`- ${o.state}: ${o.n}`);
  const list = db.prepare(`SELECT id, title, state, source FROM opportunities ORDER BY created_at DESC LIMIT 10`).all();
  if (list.length > 0) {
    P("");
    P("Most recent 10:");
    P("| id | title | state | source |");
    P("|---|---|---|---|");
    for (const o of list) P(`| \`${o.id}\` | ${o.title.slice(0, 60)} | ${o.state} | ${o.source} |`);
  }
  db.close();
} catch (e) { P(`(error: ${e.message})`); }
P("");

// --- Outbound approval queue ---
H("Outbound approval queue");
const queue = safeRead(resolve(ROOT, ".data/survival-outbound-queue.jsonl"));
if (!queue) P(`(no queue file)`);
else {
  const rows = queue.split("\n").filter(Boolean).map(l => { try { return JSON.parse(l); } catch { return null; } }).filter(Boolean);
  const pending = rows.filter(r => r.decision === null).length;
  const approved = rows.filter(r => r.decision === "approved").length;
  const denied = rows.filter(r => r.decision === "denied").length;
  P(`- total queued: ${rows.length}`);
  P(`- pending kirill decision: ${pending}`);
  P(`- approved: ${approved} (manual send required)`);
  P(`- denied: ${denied}`);
}
P("");

// --- Lead database stats ---
H("Lead database (linkedin-brand-os.sqlite)");
try {
  const db = new Database(resolve(ROOT, ".data/linkedin-brand-os.sqlite"), { readonly: true });
  const t = db.prepare(`SELECT COUNT(*) AS total,
    SUM(CASE WHEN status IN ('sent','bounced','replied') THEN 1 ELSE 0 END) AS delivered,
    SUM(CASE WHEN status='replied' THEN 1 ELSE 0 END) AS replied
    FROM outreach_emails`).get();
  P(`- outreach attempts total: ${t.total}`);
  P(`- delivered (sent/bounced/replied): ${t.delivered}`);
  P(`- replied (meaningful): ${t.replied}`);
  P(`- reply rate: ${t.delivered > 0 ? (t.replied / t.delivered * 100).toFixed(2) : 0}%`);
  const leadCount = db.prepare(`SELECT COUNT(*) AS n FROM leads`).get()?.n || 0;
  P(`- leads in db: ${leadCount}`);
  db.close();
} catch (e) { P(`(error: ${e.message})`); }
P("");

// --- Wiki brain ---
H("Wiki brain");
const wikiDir = resolve(ROOT, ".data/wiki-archive");
if (existsSync(wikiDir)) {
  const pages = readdirSync(wikiDir).filter(f => f.endsWith(".md"));
  const totalKb = pages.reduce((a, f) => a + statSync(resolve(wikiDir, f)).size, 0) / 1024;
  P(`- pages: ${pages.length}`);
  P(`- total size: ${totalKb.toFixed(1)} KB`);
  P(`- consumed by survival actions: deep_research, implementation_plan, draft_writing, growth_articulation`);
} else {
  P(`(wiki-archive directory missing)`);
}
P("");

// --- Recent bus traffic ---
H("Recent bus traffic (cortex-alive last 100 events)");
const busLog = safeRead(resolve(ROOT, ".data/cortex-alive-bus.jsonl"));
if (busLog) {
  const all = busLog.split("\n").filter(Boolean).map(l => { try { return JSON.parse(l); } catch { return null; } }).filter(Boolean);
  const last100 = all.slice(-100);
  const bySrc = {};
  for (const e of last100) bySrc[e.source] = (bySrc[e.source] || 0) + 1;
  P(`- total bus events lifetime: ${all.length}`);
  P(`- in last 100 events, top sources: ${Object.entries(bySrc).sort((a, b) => b[1] - a[1]).slice(0, 8).map(([k, v]) => `${k}(${v})`).join(", ")}`);
} else {
  P(`(no bus log)`);
}
P("");

// --- Action catalog ---
H("Substrate's action catalog");
const cat = safeRead(resolve(ROOT, "scripts/survival/action-catalog.mjs"));
if (cat) {
  const ids = [...cat.matchAll(/^\s*([a-z_]+):\s*\{[\s\S]*?\bdescription:/gm)].map(m => m[1]);
  P(`- registered actions (${ids.length}): ${ids.map(i => `\`${i}\``).join(", ")}`);
}
P("");

H("Wiring summary");
P(`- cortex-launcher boot: VERIFIED end-to-end (36 modules, 0 failures)`);
P(`- cortex-alive: holds bus alive in long-running process with auto-restart watchdog`);
P(`- pulse-daemon: hourly tick of 13 steps including survival_tick + cortex-alive watchdog`);
P(`- substrate→world bridges: web fetch, IMAP read (via perception-feeder file path), wallet read (USDC public RPC)`);
P(`- world→substrate bridges: telegram inbox jsonl, organism research INTEL.md, lead database, wiki archive`);
P(`- approval gate: outbound drafts → telegram message to kirill → manual approve cli`);

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, lines.join("\n"));
console.log(`SYSTEM-STATE.md written: ${OUT}`);
