function readOrganismRecentBeliefs() {
  if (!existsSync(ORGANISM_DB)) return [];
  try {
    const c = new Database(ORGANISM_DB, { readonly: true });
    const rows = c.prepare(`SELECT substr(claim,1,200) AS claim, ROUND(weight, 2) AS weight FROM beliefs WHERE created_at > datetime('now', '-14 days') AND weight > 0.6 ORDER BY weight DESC LIMIT 10`).all();
    c.close();
    return rows;
  } catch { return []; }
}

function readRecentPostTemplates() {
  if (!existsSync(PRIMARY_DB)) return [];
  try {
    const c = new Database(PRIMARY_DB, { readonly: true });
    const rows = c.prepare(`SELECT template_type, accent_color, COUNT(*) AS n FROM content_visual_assets WHERE created_at > datetime('now', '-30 days') GROUP BY template_type, accent_color ORDER BY n DESC LIMIT 10`).all();
    c.close();
    return rows;
  } catch { return []; }
}

function readAwarenessHeadlines() {
  if (!existsSync(AWARENESS_LATEST)) return [];
  try {
    const content = readFileSync(AWARENESS_LATEST, "utf-8");
    const headers = (content.match(/^### .+/gm) || []).slice(0, 8).map(l => l.replace(/^###\s+/, ""));
    return headers;
  } catch { return []; }
}

function buildTrendsDoc() {
  const beliefs = readOrganismRecentBeliefs();
  const templates = readRecentPostTemplates();
  const awareness = readAwarenessHeadlines();

  let md = `# Trend Feed — Refreshed ${new Date().toISOString().slice(0, 10)}\n\n`;
  md += `Auto-generated by \`scripts/content/trend-feed.mjs\`. Read by trend-watcher persona on every consultation.\n\n`;
  md += `---\n\n`;
  md += CURATED_TRENDS_Q2_2026;
  md += `\n\n## Substrate-internal trends (last 14d organism beliefs, weight > 0.6)\n\n`;
  if (beliefs.length === 0) md += `_No fresh high-weight beliefs._\n`;
  else for (const b of beliefs) md += `- (w=${b.weight}) ${b.claim}\n`;

  md += `\n## Substrate's own visual usage (last 30d)\n\n`;
  if (templates.length === 0) md += `_No assets generated yet in last 30d._\n`;
  else {
    md += `| Template | Accent | Count |\n|---|---|---|\n`;
    for (const t of templates) md += `| ${t.template_type || "?"} | ${t.accent_color || "?"} | ${t.n} |\n`;
  }

  md += `\n## Awareness-flagged hot topics (latest brief)\n\n`;
  if (awareness.length === 0) md += `_Awareness brief unavailable._\n`;
  else for (const h of awareness) md += `- ${h}\n`;

  md += `\n---\n_Trend-watcher: cite this file when consulting on viz decisions. If older than 30 days, downgrade confidence._\n`;
  return md;
}

export function refreshTrends() {
  mkdirSync(dirname(TRENDS_PATH), { recursive: true });
  const md = buildTrendsDoc();
  writeFileSync(TRENDS_PATH, md);
  return { ok: true, path: TRENDS_PATH.replace(ROOT + "/", ""), bytes: md.length };
}

export function getCurrentTrends() {
  if (!existsSync(TRENDS_PATH)) return null;
  return { content: readFileSync(TRENDS_PATH, "utf-8"), age_days: (Date.now() - statSync(TRENDS_PATH).mtimeMs) / 86400000 };
}

// CLI
if (import.meta.url === `file://${process.argv[1]}`) {
  const cmd = process.argv[2] || "refresh";
  if (cmd === "refresh") {
    const r = refreshTrends();
    console.log(`✓ trends refreshed → ${r.path} (${r.bytes} bytes)`);
  } else if (cmd === "cat") {
    const t = getCurrentTrends();
    if (!t) console.log("no trends file yet; run `refresh`");
    else console.log(t.content);
  } else { console.error("Usage: trend-feed.mjs refresh|cat"); process.exit(2); }
}
